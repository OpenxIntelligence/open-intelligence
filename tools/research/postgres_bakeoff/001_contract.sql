CREATE OR REPLACE FUNCTION ehr.validate_note_lineage()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog,ehr AS $lineage$
BEGIN
  IF (NEW.version=1 AND NEW.supersedes_id IS NOT NULL)
     OR (NEW.version>1 AND NEW.supersedes_id IS NULL) THEN
    RAISE EXCEPTION 'OI-NOTE-LINEAGE: expected direct predecessor';
  END IF;
  IF NEW.version>1 AND NOT EXISTS (
    SELECT 1 FROM ehr.clinical_note_versions p
    WHERE p.id=NEW.supersedes_id AND p.note_id=NEW.note_id
      AND p.version=NEW.version-1
  ) THEN
    RAISE EXCEPTION 'OI-NOTE-LINEAGE: predecessor must belong to the same note';
  END IF;
  IF NEW.status IN ('draft_correction','attested_correction')
     AND COALESCE(NULLIF(btrim(NEW.amendment_reason),''),'')='' THEN
    RAISE EXCEPTION 'OI-NOTE-LINEAGE: correction reason is required';
  END IF;
  RETURN NEW;
END;
$lineage$;
CREATE OR REPLACE TRIGGER oi_note_lineage_insert
 BEFORE INSERT ON ehr.clinical_note_versions
 FOR EACH ROW EXECUTE FUNCTION ehr.validate_note_lineage();

