CREATE TABLE IF NOT EXISTS identity.identity_patients (
  patient_id text PRIMARY KEY CHECK (char_length(patient_id) BETWEEN 3 AND 128),
  origin_org text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by text NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision >= 1)
);
-- This is a test-only *database-role* authorization fixture. Real authenticated
-- user + purpose/consent policy belongs to PF-01/PF-02 and is NOT implemented.
CREATE TABLE IF NOT EXISTS auth.role_patient_grants (
  database_role name NOT NULL,
  patient_id text NOT NULL REFERENCES identity.identity_patients(patient_id),
  purpose text NOT NULL CHECK (purpose IN ('care','operations','research')),
  revoked_at timestamptz,
  PRIMARY KEY (database_role,patient_id,purpose)
);

CREATE OR REPLACE FUNCTION auth.can_access_patient(_patient_id text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog,auth,identity
AS $policy$
  SELECT EXISTS (
    SELECT 1 FROM auth.role_patient_grants g
    JOIN identity.identity_patients p ON p.patient_id = g.patient_id
    WHERE g.database_role = SESSION_USER::name
      AND g.patient_id = _patient_id
      AND g.purpose = NULLIF(current_setting('oi.request_purpose', true), '')
      AND g.revoked_at IS NULL
      AND p.status = 'active'
  );
$policy$;
REVOKE ALL ON FUNCTION auth.can_access_patient(text) FROM PUBLIC;

