-- OI B-01b PostgreSQL patient registry port: extension of 001_contract.sql.
-- DISPOSABLE TEST SCHEMA, NOT production identity/consent/PHI clearance.
-- One canonical identity.identity_patients table only; no second patient master.
CREATE TABLE IF NOT EXISTS identity.identity_create_receipts (
 origin_org text NOT NULL,
 request_key text NOT NULL,
 request_digest char(64) NOT NULL CHECK (request_digest ~ '^[0-9a-f]{64}$'),
 patient_id text NOT NULL REFERENCES identity.identity_patients(patient_id),
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(origin_org,request_key)
);
CREATE INDEX IF NOT EXISTS idx_b01b_identity_origin ON identity.identity_patients(origin_org,created_at,patient_id);
CREATE TABLE IF NOT EXISTS identity.identity_domain_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id text NOT NULL REFERENCES identity.identity_patients(patient_id),
 event_type text NOT NULL CHECK (char_length(event_type) BETWEEN 3 AND 100),
 metadata_json jsonb NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT now(),
 CHECK (jsonb_typeof(metadata_json)='object')
);
CREATE INDEX IF NOT EXISTS idx_b01b_identity_events ON identity.identity_domain_events(patient_id,id);

CREATE OR REPLACE FUNCTION identity.reject_registry_history_mutation()
RETURNS trigger LANGUAGE plpgsql AS $immutable$
BEGIN
 RAISE EXCEPTION 'OI-IDENTITY-HISTORY-IMMUTABLE: append a new record';
END;
$immutable$;
CREATE OR REPLACE TRIGGER oi_identity_receipts_no_update
 BEFORE UPDATE ON identity.identity_create_receipts
 FOR EACH ROW EXECUTE FUNCTION identity.reject_registry_history_mutation();
CREATE OR REPLACE TRIGGER oi_identity_receipts_no_delete
 BEFORE DELETE ON identity.identity_create_receipts
 FOR EACH ROW EXECUTE FUNCTION identity.reject_registry_history_mutation();
CREATE OR REPLACE TRIGGER oi_identity_events_no_update
 BEFORE UPDATE ON identity.identity_domain_events
 FOR EACH ROW EXECUTE FUNCTION identity.reject_registry_history_mutation();
CREATE OR REPLACE TRIGGER oi_identity_events_no_delete
 BEFORE DELETE ON identity.identity_domain_events
 FOR EACH ROW EXECUTE FUNCTION identity.reject_registry_history_mutation();

-- DO NOT grant this schema's write privileges to patient/user/login roles.
-- B-01b exercises migrations as its ephemeral postgres CI DBA. In production,
-- an approved dedicated identity service role, revocable consent and RLS/PEP
-- policies are required before any patient data can be accepted.

CREATE OR REPLACE FUNCTION identity.guard_registration_receipt()
RETURNS trigger LANGUAGE plpgsql AS $guard$
BEGIN
 IF NOT EXISTS (
    SELECT 1 FROM identity.identity_patients p
    WHERE p.patient_id=NEW.patient_id AND p.origin_org=NEW.origin_org
 ) THEN
    RAISE EXCEPTION 'OI-REGISTRY-ORG: receipt patient must belong to organization';
 END IF;
 RETURN NEW;
END;
$guard$;
CREATE OR REPLACE TRIGGER oi_registry_receipt_check_origin
 BEFORE INSERT ON identity.identity_create_receipts
 FOR EACH ROW EXECUTE FUNCTION identity.guard_registration_receipt();

-- The patient id, original assigner and creation receipt are canonical history.
-- A suspension changes status only through one monotonic revision transition.
CREATE OR REPLACE FUNCTION identity.guard_patient_identity_mutation()
RETURNS trigger LANGUAGE plpgsql AS $guard$
BEGIN
 IF OLD.patient_id IS DISTINCT FROM NEW.patient_id
    OR OLD.origin_org IS DISTINCT FROM NEW.origin_org
    OR OLD.created_by IS DISTINCT FROM NEW.created_by
    OR OLD.created_at IS DISTINCT FROM NEW.created_at THEN
   RAISE EXCEPTION 'OI-PATIENT-IDENTITY-IMMUTABLE: new identity requires a reviewed link';
 END IF;
 IF NOT (OLD.status='active' AND NEW.status='suspended'
         AND NEW.revision=OLD.revision+1) THEN
   RAISE EXCEPTION 'OI-PATIENT-STATE: only active to suspended with monotonic revision';
 END IF;
 RETURN NEW;
END;
$guard$;
CREATE OR REPLACE TRIGGER oi_patient_identity_guard
 BEFORE UPDATE ON identity.identity_patients
 FOR EACH ROW EXECUTE FUNCTION identity.guard_patient_identity_mutation();
